BUFFER_FILE = Path(__file__).resolve().parent / "sensor_buffer.json"

def generate_scenario_reading(
    station: Dict[str, Any],
    scenario: str,
    target_station_id: str,
    cycle: int
) -> Dict[str, Any]:
    """
    Generate telemetry reading. If station is target_station_id, apply deterministic
    scenario parameters. Otherwise generate normal baseline telemetry.
    """
    is_target = (station["sensor_id"] == target_station_id)
    
    # Baseline defaults (deterministic center + minimal fluctuation)
    moisture = station["base_moisture"]
    pore_p = station["base_pore_p"]
    vib = station["base_vib"]
    rainfall_1h = 0.0
    temp = station["base_temp"]

    scenario_label = "normal"

    if is_target:
        scenario_label = scenario
        if scenario == "normal":
            # Normal baseline
            moisture = round(station["base_moisture"] + (cycle % 3) * 0.2, 1)
            pore_p = round(station["base_pore_p"] + (cycle % 3) * 0.1, 2)
            vib = round(station["base_vib"] + 0.005 * (cycle % 2), 3)
            rainfall_1h = 0.0

        elif scenario == "rainfall":
            # Simulated heavy rainfall event: IMD heavy rainfall threshold demo
            # Demonstrates temporal window rainfall accumulation
            rainfall_1h = round(15.0 + cycle * 5.0, 1)
            moisture = round(station["base_moisture"] + cycle * 2.5, 1)
            pore_p = round(station["base_pore_p"] + cycle * 1.2, 2)
            vib = round(station["base_vib"] + 0.02, 3)

        elif scenario == "moisture":
            # Deterministic demo parameter: moisture escalation > 45% and positive rate
            moisture = round(48.0 + min(cycle * 4.0, 25.0), 1)
            pore_p = round(station["base_pore_p"] + cycle * 1.5, 2)
            vib = round(station["base_vib"] + 0.02, 3)

        elif scenario == "pore_pressure":
            # Deterministic demo parameter: pore pressure escalation > 28 kPa
            moisture = round(station["base_moisture"] + 10.0, 1)
            pore_p = round(29.5 + min(cycle * 2.0, 15.0), 2)
            vib = round(station["base_vib"] + 0.03, 3)

        elif scenario == "vibration":
            # Deterministic demo parameter: ground vibration > 3x baseline
            moisture = station["base_moisture"]
            pore_p = station["base_pore_p"]
            vib = round(station["base_vib"] * 3.8 + cycle * 0.05, 3)

        elif scenario == "deterioration":
            # Compound progressive deterioration across multiple cycles
            moisture = round(station["base_moisture"] + cycle * 6.0, 1)
            pore_p = round(station["base_pore_p"] + cycle * 4.0, 2)
            vib = round(station["base_vib"] + cycle * 0.08, 3)
            rainfall_1h = round(10.0 + cycle * 8.0, 1)

        elif scenario == "override":
            # Critical extreme values configured to trigger temporal safety override
            moisture = 88.5
            pore_p = 42.0
            vib = 0.85
            rainfall_1h = 65.0

    return {
        "sensor_id": station["sensor_id"],
        "latitude": station["latitude"],
        "longitude": station["longitude"],
        "soil_moisture": moisture,
        "temperature": temp,
        "pore_pressure": pore_p,
        "ground_vibration": vib,
        "battery_level": 95,
        "signal_strength": -65,
        "is_simulated": True,
        "scenario_applied": scenario_label,
        "provenance_notice": "Simulation scenario parameter (Category C: Demo/Heuristic)",
        "timestamp": datetime.now(timezone.utc).isoformat()
    }

def push_to_backend(url: str, payload: dict) -> bool:
    endpoint = f"{url.rstrip('/')}/api/sensors/data"
    try:
        resp = requests.post(endpoint, json=payload, timeout=3.0)
        return resp.status_code in [200, 201]
    except Exception:
        return False

def buffer_reading(payload: dict):
    buffer = []
    if BUFFER_FILE.exists():
        try:
            with open(BUFFER_FILE, "r", encoding="utf-8") as f:
                buffer = json.load(f)
        except Exception:
            buffer = []
    buffer.append(payload)
    with open(BUFFER_FILE, "w", encoding="utf-8") as f:
        json.dump(buffer, f, indent=2)

def flush_buffer(url: str):
    if not BUFFER_FILE.exists():
        return
    try:
        with open(BUFFER_FILE, "r", encoding="utf-8") as f:
            buffer = json.load(f)
    except Exception:
        return

    if not buffer:
        return

    print(f"[SIMULATED TELEMETRY BUFFER] Attempting to flush {len(buffer)} buffered offline readings...")
    sync_items = []
    for idx, item in enumerate(buffer):
        sync_items.append({
            "local_id": f"SENSOR-BUF-{int(time.time())}-{idx}",
            "device_id": item["sensor_id"],
            "entity_type": "sensor_reading",
            "payload": item,
            "client_created_at": item.get("timestamp")
        })

    try:
        sync_url = f"{url.rstrip('/')}/api/sync/push"
        resp = requests.post(sync_url, json={"items": sync_items}, timeout=5.0)
        if resp.status_code == 200:
            print(f"[SIMULATED TELEMETRY BUFFER] Flushed {len(buffer)} readings to server sync engine.")
            BUFFER_FILE.unlink(missing_ok=True)
        else:
            print(f"[SIMULATED TELEMETRY BUFFER] Server returned status {resp.status_code}. Retaining buffer.")
    except Exception as e:
        print(f"[SIMULATED TELEMETRY BUFFER] Could not reach sync endpoint: {e}")

